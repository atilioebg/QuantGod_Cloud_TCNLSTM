import os
import sys
import subprocess
import yaml
import logging
from pathlib import Path
import gc

# Add project root to path
project_root = str(Path(__file__).parents[4])
if project_root not in sys.path:
    sys.path.append(project_root)

from src.cloud.base_model.utils.logging_utils import setup_logger

logger = logging.getLogger(__name__)

def free_memory():
    """Implements aggressive garbage collection to prevent VRAM spikes across phases."""
    logger.info("🧹 Initiating deep memory sweep (gc.collect and torch.cuda.empty_cache)...")
    gc.collect()
    try:
        import torch
        if torch.cuda.is_available():
            torch.cuda.empty_cache()
            logger.info("  ↳ CUDA VRAM cache cleared.")
    except ImportError:
        pass

